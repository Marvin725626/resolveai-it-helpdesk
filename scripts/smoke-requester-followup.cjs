const assert = require('node:assert/strict');
const { randomBytes } = require('node:crypto');
const { createRequire } = require('node:module');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const requireFrontend = createRequire(path.join(root, 'frontend/package.json'));
const { chromium } = process.env.PLAYWRIGHT_MODULE ? require(process.env.PLAYWRIGHT_MODULE) : requireFrontend('playwright');
const webUrl = process.env.RESOLVEAI_URL || 'http://127.0.0.1:5297';
const apiUrl = process.env.RESOLVEAI_API_URL || 'http://127.0.0.1:8197/api/v1';
(async () => {
  const suffix = Date.now().toString(36);
  const password = randomBytes(16).toString('hex') + 'Aa1!';
  const ownerEmail = `requester-${suffix}@example.com`;
  const supportEmail = `support-${suffix}@example.com`;
  async function api(route, method = 'GET', body, token) {
    const response = await fetch(apiUrl + route, {method, headers: {'Content-Type':'application/json', ...(token ? {Authorization: 'Bearer ' + token} : {})}, ...(body ? {body:JSON.stringify(body)} : {})});
    assert(response.ok, `${method} ${route}: ${response.status}`);
    return response.json();
  }
  const owner = await api('/auth/register','POST',{email:ownerEmail,password,full_name:'演示报障人',tenant_name:'报障跟进演示',tenant_slug:'follow-'+suffix});
  const invite = await api('/auth/invitations','POST',{email:supportEmail},owner.access_token);
  const support = await api('/auth/invitations/accept','POST',{token:invite.token,email:supportEmail,password,full_name:'演示支持专员'});
  const browser = await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_PATH || undefined});
  const errors=[];
  const requesterContext = await browser.newContext({viewport:{width:1440,height:1100},locale:'zh-CN'});
  const supportContext = await browser.newContext({viewport:{width:1440,height:1100},locale:'zh-CN'});
  const requesterPage=await requesterContext.newPage();const supportPage=await supportContext.newPage();
  for(const page of [requesterPage,supportPage]) page.on('pageerror',error=>errors.push(error.message));
  async function login(page,email){ await page.goto(webUrl);await page.getByLabel('工作邮箱').fill(email);await page.getByLabel('密码',{exact:true}).fill(password);await page.getByRole('button',{name:'进入工作台'}).click();await page.getByRole('button',{name:'智能诊断',exact:true}).waitFor(); }
  try {
    await login(requesterPage,ownerEmail);
    await requesterPage.locator('#question').fill('VPN 认证超时，请转人工处理');
    await requesterPage.getByRole('button',{name:'开始诊断',exact:true}).click();
    await requesterPage.getByRole('button',{name:'跟进这张工单',exact:true}).waitFor();
    await requesterPage.getByRole('button',{name:'跟进这张工单',exact:true}).click();
    await requesterPage.getByRole('button',{name:'刷新进度',exact:true}).waitFor();
    const mine=await api('/helpdesk/my-tickets','GET',undefined,owner.access_token);
    const ticketId=mine.items[0].id;
    await login(supportPage,supportEmail);
    await supportPage.getByRole('button',{name:'工单队列',exact:true}).click();
    const card=supportPage.locator('.ticket-card').filter({hasText:ticketId.slice(0,8)});
    await card.getByRole('button',{name:'接手处理',exact:true}).click();
    await card.getByRole('button',{name:'标记解决',exact:true}).waitFor();
    await card.locator('summary').first().click();
    await card.getByLabel('公开回复',{exact:true}).fill('请补充错误提示出现的时间和网络环境。');
    const replyQueueRefresh = supportPage.waitForResponse(r => r.url().includes('/helpdesk/ticket-queue?') && r.status() === 200);
    await card.getByRole('button',{name:'发送公开回复',exact:true}).click();
    await (await replyQueueRefresh).finished();
    await supportPage.waitForFunction(() => !document.body.innerText.includes('正在更新工单列表…'));
    await card.getByText('请补充错误提示出现的时间和网络环境。',{exact:true}).waitFor();
    await card.getByRole('button',{name:'等待员工反馈',exact:true}).click();
    await card.getByRole('button',{name:'继续处理',exact:true}).waitFor();
    await requesterPage.getByRole('button',{name:'刷新进度',exact:true}).click();
    await requesterPage.getByText('请补充错误提示出现的时间和网络环境。',{exact:true}).waitFor();
    await requesterPage.getByText(/来源：AI 转人工 · 状态：等待补充/).waitFor();
    await requesterPage.getByLabel('补充资料',{exact:true}).fill('今天上午九点，在公司无线网络中出现认证超时。');
    await requesterPage.getByRole('button',{name:'发送补充',exact:true}).click();
    await requesterPage.getByText('今天上午九点，在公司无线网络中出现认证超时。',{exact:true}).waitFor();
    await requesterPage.getByText(/来源：AI 转人工 · 状态：处理中/).waitFor();
    await requesterPage.screenshot({path:process.env.RESOLVEAI_SCREENSHOT || path.join(root,'docs/resolveai-my-requests.png'),fullPage:true});
    await supportPage.getByRole('button',{name:'刷新列表',exact:true}).click();
    await card.getByRole('button',{name:'标记解决',exact:true}).waitFor();
    await card.getByText('今天上午九点，在公司无线网络中出现认证超时。',{exact:true}).waitFor();
    await card.getByRole('button',{name:'标记解决',exact:true}).click();
    await card.getByRole('button',{name:'关闭工单',exact:true}).waitFor();
    await requesterPage.getByRole('button',{name:'刷新进度',exact:true}).click();
    await requesterPage.getByRole('button',{name:'确认解决并关闭',exact:true}).click();
    await requesterPage.getByText('已确认解决并关闭工单。',{exact:true}).waitFor();
    assert.equal(await requesterPage.getByLabel('补充资料',{exact:true}).count(),0);
    await supportPage.getByRole('button',{name:'刷新列表',exact:true}).click();
    await card.getByText('工单已关闭，公开沟通为只读。',{exact:true}).waitFor();
    assert.equal(await card.getByLabel('公开回复',{exact:true}).count(),0);
    const fresh=await api(`/helpdesk/my-tickets/${ticketId}`,'GET',undefined,owner.access_token);
    assert.equal(fresh.ticket.status,'CLOSED');
    await requesterPage.setViewportSize({width:390,height:844});
    assert(await requesterPage.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
    assert.deepEqual(errors,[]);
    console.log(JSON.stringify({passed:true,workflow:'AI escalation → support claim/public question/wait → requester refresh/supplement → support resolve → requester confirm close',closed_public_readonly:true,mobile_width:390,page_errors:errors.length}));
  } finally { await browser.close(); }
})().catch(error=>{console.error(error);process.exitCode=1;});
