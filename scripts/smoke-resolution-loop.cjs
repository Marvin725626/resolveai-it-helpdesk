const assert = require('node:assert/strict');
const { randomBytes } = require('node:crypto');
const { createRequire } = require('node:module');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const requireFrontend = createRequire(path.join(root, 'frontend/package.json'));
const { chromium } = process.env.PLAYWRIGHT_MODULE ? require(process.env.PLAYWRIGHT_MODULE) : requireFrontend('playwright');
const webUrl = process.env.RESOLVEAI_URL || 'http://127.0.0.1:5299';
const apiUrl = process.env.RESOLVEAI_API_URL || 'http://127.0.0.1:8199/api/v1';
(async () => {
  const suffix = Date.now().toString(36), password = randomBytes(16).toString('hex') + 'Aa1!';
  const ownerEmail = `loop-owner-${suffix}@example.com`, supportEmail = `loop-support-${suffix}@example.com`;
  async function api(route, method='GET', body, token) {
    const response = await fetch(apiUrl+route,{method,headers:{'Content-Type':'application/json',...(token?{Authorization:'Bearer '+token}:{})},...(body?{body:JSON.stringify(body)}:{})});
    assert(response.ok,`${method} ${route}: ${response.status}`);return response.json();
  }
  const owner = await api('/auth/register','POST',{email:ownerEmail,password,full_name:'演示报障人',tenant_name:'解决与知识闭环演示',tenant_slug:'resolution-loop-'+suffix});
  const invite = await api('/auth/invitations','POST',{email:supportEmail},owner.access_token);
  const support = await api('/auth/invitations/accept','POST',{token:invite.token,email:supportEmail,password,full_name:'演示支持专员'});
  const run = await api('/helpdesk/runs','POST',{request_id:crypto.randomUUID(),question:'蓝鲸VPN认证超时，请人工处理'},owner.access_token);
  const ticketId=run.ticket_id;assert(ticketId);
  const privateFixture='INTERNAL-ONLY-FIXTURE-'+suffix;
  await api(`/helpdesk/tickets/${ticketId}/notes`,'POST',{request_id:crypto.randomUUID(),note:privateFixture},owner.access_token);
  const browser = await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_PATH||undefined});
  const ownerContext=await browser.newContext({viewport:{width:1440,height:1100},locale:'zh-CN'}), supportContext=await browser.newContext({viewport:{width:1440,height:1100},locale:'zh-CN'});
  const ownerPage=await ownerContext.newPage(), supportPage=await supportContext.newPage();
  const errors=[];for(const page of [ownerPage,supportPage])page.on('pageerror',error=>errors.push(error.message));
  async function login(page,email) {await page.goto(webUrl);await page.getByLabel('工作邮箱').fill(email);await page.getByLabel('密码',{exact:true}).fill(password);await page.getByRole('button',{name:'进入工作台'}).click();await page.getByRole('button',{name:'我的报障',exact:true}).waitFor();}
  try {
    await login(supportPage,supportEmail);
    await supportPage.getByRole('button',{name:/^工单队列/}).click();
    const card=supportPage.locator('.ticket-card').filter({hasText:ticketId.slice(0,8)});
    await card.getByRole('button',{name:'接手处理',exact:true}).click();
    await card.getByRole('button',{name:'填写解决记录',exact:true}).click();
    async function solve(summary,steps) {
      await card.locator('[id^="resolution-category-"]').selectOption('service');
      await card.getByLabel('公开解决摘要',{exact:true}).fill(summary);
      await card.getByLabel('公开排查步骤（可选）',{exact:true}).fill(steps);
      const response=supportPage.waitForResponse(r=>r.url().endsWith(`/tickets/${ticketId}/resolve`)&&r.request().method()==='POST');
      await card.getByRole('button',{name:'保存解决记录并标记解决',exact:true}).click();
      const saved=await response;assert.equal(saved.status(),201);return (await saved.json()).resolution;
    }
    const first=await solve('已调整蓝鲸VPN配置，请报障人验证。','检查服务状态。\n调整客户端连接配置。');
    await login(ownerPage,ownerEmail);await ownerPage.getByRole('button',{name:'我的报障',exact:true}).click();
    const personal=ownerPage.getByRole('region',{name:'公开解决与验收评价',exact:true});
    await personal.getByText(first.summary,{exact:true}).waitFor();
    assert(!(await ownerPage.locator('body').innerText()).includes(privateFixture));
    await ownerPage.getByLabel('仍未解决时说明原因',{exact:true}).fill('切换网络后仍有认证错误，请继续排查。');
    await ownerPage.getByRole('button',{name:'仍未解决，重新处理',exact:true}).click();
    await ownerPage.getByText('已告知支持人员问题仍未解决。',{exact:true}).waitFor();
    await supportPage.getByRole('button',{name:'刷新列表',exact:true}).click();
    const second=await solve('已修复蓝鲸VPN认证缓存，重新连接验证成功。','清理过期认证缓存。\n重建VPN连接。\n在两种网络下验证认证与内网访问。');
    assert.notEqual(first.id,second.id);
    await ownerPage.getByRole('button',{name:'刷新进度',exact:true}).click();
    await personal.getByText(second.summary,{exact:true}).waitFor();
    await ownerPage.getByRole('button',{name:'确认解决并关闭',exact:true}).click();
    await ownerPage.getByText('已确认解决并关闭工单。',{exact:true}).waitFor();
    await personal.locator('[id^="resolution-rating-"]').selectOption('5');
    await personal.getByLabel('评价短评（可选）',{exact:true}).fill('公开处理说明清楚，验证后已恢复。');
    await personal.getByRole('button',{name:'提交本轮评价',exact:true}).click();
    await personal.getByText('本轮评价：5 / 5',{exact:true}).waitFor();
    const resolved=await api(`/helpdesk/my-tickets/${ticketId}/resolution`,'GET',undefined,owner.access_token);
    assert.equal(resolved.resolution.id,second.id);assert.equal(resolved.satisfaction.rating,5);
    await ownerPage.setViewportSize({width:390,height:844});
    assert(await ownerPage.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
    await ownerPage.screenshot({path:path.join(root,'docs/resolveai-resolution-feedback.png'),fullPage:true});
    await ownerPage.setViewportSize({width:1440,height:1100});
    await supportPage.getByRole('button',{name:'刷新列表',exact:true}).click();
    const action=card.locator('.knowledge-draft-action');
    const title='蓝鲸VPN认证缓存故障处理方法';
    await action.getByLabel('草稿标题',{exact:true}).fill(title);
    const initialContent=await action.getByLabel('知识正文').inputValue();
    assert(initialContent.includes(second.summary)&&!initialContent.includes(privateFixture));
    await action.getByLabel('检索关键词',{exact:true}).fill('蓝鲸VPN 认证缓存 内网访问');
    const createdResponse=supportPage.waitForResponse(r=>r.url().endsWith('/helpdesk/knowledge-drafts')&&r.request().method()==='POST');
    await action.getByRole('button',{name:'保存知识草稿',exact:true}).click();
    const created=await createdResponse;assert.equal(created.status(),201);
    await action.getByText('知识草稿已保存，等待工作区管理员审核；草稿不会参与检索。',{exact:true}).waitFor();
    assert.equal((await api('/helpdesk/knowledge/search','POST',{query:'蓝鲸VPN认证缓存'},owner.access_token)).results.length,0);
    await ownerPage.getByRole('button',{name:'知识库',exact:true}).click();
    const review=ownerPage.locator('.knowledge-drafts-panel');
    await review.getByLabel('草稿标题',{exact:true}).waitFor();
    await review.getByLabel('审核说明',{exact:true}).fill('请补充验证步骤后重新提交。');
    await review.getByRole('button',{name:'驳回',exact:true}).click();
    await review.getByText('草稿已驳回；作者可以修改后重新提交。',{exact:true}).waitFor();
    await supportPage.getByRole('button',{name:'知识库',exact:true}).click();
    const author=supportPage.locator('.knowledge-drafts-panel');
    await author.getByLabel('知识正文').fill(initialContent+'\n验证：再次连接并确认内网访问正常。');
    await author.getByRole('button',{name:'保存草稿',exact:true}).click();
    await author.getByText('草稿已保存；已驳回的草稿回到待审核状态。',{exact:true}).waitFor();
    await review.getByRole('button',{name:'刷新',exact:true}).click();
    await review.getByLabel('审核说明',{exact:true}).fill('已核对公开内容与验证步骤，可以发布。');
    const publishedResponse=ownerPage.waitForResponse(r=>/\/knowledge-drafts\/[^/]+\/publish$/.test(r.url())&&r.request().method()==='POST');
    await review.getByRole('button',{name:'审核并发布',exact:true}).click();
    const published=await publishedResponse;assert.equal(published.status(),200);const result=await published.json();
    await review.getByText(`已发布：${result.source_code} v${result.source_version}`,{exact:true}).waitFor();
    const searched=await api('/helpdesk/knowledge/search','POST',{query:'蓝鲸VPN认证缓存'},owner.access_token);
    assert(searched.results.some(row=>row.code===result.source_code));
    assert(!JSON.stringify(searched).includes(privateFixture));
    await ownerPage.getByLabel('检索测试问题',{exact:true}).fill('蓝鲸VPN认证缓存');
    await ownerPage.getByRole('button',{name:'测试检索',exact:true}).click();
    await ownerPage.locator('.retrieval-results').getByText(title,{exact:true}).waitFor();
    await review.screenshot({path:path.join(root,'docs/resolveai-knowledge-draft.png')});
    assert.deepEqual(errors,[]);
    console.log(JSON.stringify({passed:true,workflow:'two resolution rounds → requester confirms and rates current round → support draft → admin reject → author revise → admin publish → retrieval hit',resolution_rounds:2,rating:5,published_code:result.source_code,drafts_excluded_before_publish:true,private_note_not_copied:true,mobile_width:390,page_errors:errors.length}));
  } finally {await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
