const fs=require('node:fs/promises');
const path=require('node:path');
const assert=require('node:assert/strict');
const {createRequire}=require('node:module');
const root=process.env.RESOLVEAI_ROOT||path.resolve(__dirname,'..');
const requireFrontend=createRequire(path.join(root,'frontend/package.json'));
const {chromium}=process.env.PLAYWRIGHT_MODULE?require(process.env.PLAYWRIGHT_MODULE):requireFrontend('playwright');
(async()=>{
  const browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_PATH||undefined});
  const context=await browser.newContext({viewport:{width:1440,height:1100},acceptDownloads:true,locale:'zh-CN'});
  const page=await context.newPage();const errors=[];page.on('pageerror',error=>errors.push(error.message));
  const code='DNS-'+(Math.floor(Date.now()/1000)%90000+10000);
  async function api(endpoint){return page.evaluate(async endpoint=>{const response=await fetch('/api/v1'+endpoint,{headers:{Authorization:'Bearer '+localStorage.getItem('resolveai_token')}});if(!response.ok)throw new Error('API read failed '+response.status);return response.json();},endpoint);}
  try{
    await page.goto(process.env.RESOLVEAI_URL||'http://127.0.0.1:5174');
    await page.getByLabel('工作邮箱').fill(process.env.RESOLVEAI_EMAIL||'demo@resolveai.example.com');
    await page.getByLabel('密码',{exact:true}).fill(process.env.RESOLVEAI_PASSWORD||'ResolveAI123!');
    await page.getByRole('button',{name:'进入工作台'}).click();
    await page.getByRole('heading',{name:'让 IT 问题更快得到响应'}).waitFor();
    await page.getByRole('button',{name:'知识库',exact:true}).click();
    await page.getByRole('button',{name:'新增来源',exact:true}).click();
    await page.getByLabel('来源代码',{exact:true}).fill(code);
    await page.getByLabel('导入 Markdown / TXT',{exact:true}).setInputFiles(path.join(root,'docs/samples/dns-check.md'));
    await page.getByLabel('知识标题',{exact:true}).fill('DNS 解析故障检查手册');
    await page.getByLabel('检索关键词',{exact:true}).fill('DNS 网络 解析 DNSProbe');
    await page.getByRole('button',{name:'保存并更新索引',exact:true}).click();
    await page.getByText('知识已保存，检索索引已同步更新。',{exact:true}).waitFor();
    await page.getByLabel('搜索知识来源').fill(code);
    const row=page.locator('.source-row').filter({hasText:code});
    assert.equal(await row.count(),1);
    await row.getByRole('button',{name:'编辑 / 版本',exact:true}).click();
    const original=await page.getByLabel('知识正文').inputValue();
    await page.getByLabel('知识正文').fill(original+'\n\nDNSProbe 演示更新：记录解析错误，再交由网络团队确认。');
    await page.getByRole('button',{name:'保存并更新索引',exact:true}).click();
    await page.getByText('知识已保存，检索索引已同步更新。',{exact:true}).waitFor();
    const before=await api('/helpdesk/overview');
    await page.getByLabel('检索测试问题').fill('DNSProbe DNS 解析故障排查');
    await page.getByRole('button',{name:'测试检索',exact:true}).click();
    await page.locator('.retrieval-results article').filter({hasText:code}).getByRole('heading',{name:'DNS 解析故障检查手册'}).waitFor();
    const after=await api('/helpdesk/overview');assert.equal(before.runs,after.runs);assert.equal(before.open_tickets,after.open_tickets);
    await page.screenshot({path:path.join(root,'docs/resolveai-retrieval-lab.png'),fullPage:true});
    await row.getByRole('button',{name:'停用',exact:true}).click();
    await page.getByText('知识已停用，不再参与检索；历史诊断引用保留。',{exact:true}).waitFor();
    assert(!(await api('/helpdesk/runbooks')).some(item=>item.code===code));
    await row.getByRole('button',{name:'编辑 / 版本',exact:true}).click();
    const revision=page.locator('.revision-list details').filter({has:page.locator('summary').filter({hasText:/^v1 ·/})});
    await revision.locator('summary').click();
    await revision.getByRole('button',{name:'恢复该版本为新版本',exact:true}).click();
    await page.getByText('已将历史内容保存为一个新版本。',{exact:true}).waitFor();
    const restored=(await api('/helpdesk/knowledge')).find(item=>item.code===code);
    assert.equal(restored.version,4);assert.equal(restored.content,original);assert(restored.active);
    await row.getByRole('button',{name:'编辑 / 版本',exact:true}).click();
    await page.locator('.revision-list details').first().waitFor();
    await page.screenshot({path:path.join(root,'docs/resolveai-knowledge-versions.png'),fullPage:true});
    const pendingDownload=page.waitForEvent('download');await page.getByRole('button',{name:'导出知识',exact:true}).click();
    const exported=JSON.parse(await fs.readFile(await(await pendingDownload).path(),'utf8'));
    assert.equal(exported.format,'resolveai-knowledge-v1');assert(exported.sources.some(item=>item.code===code));
    await page.setViewportSize({width:390,height:844});
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    await page.screenshot({path:path.join(root,'docs/resolveai-knowledge-mobile.png'),fullPage:true});
    await page.setViewportSize({width:1440,height:1100});
    await page.getByRole('button',{name:'智能诊断',exact:true}).click();
    const ticketCount=(await api('/helpdesk/overview')).open_tickets;
    // Drop the real stream only after the server finishes it. The UI must read the original result, not resubmit.
    await page.route('**/api/v1/helpdesk/runs/stream',async route=>{await route.fetch();await route.abort('connectionfailed');});
    await page.getByLabel('描述 IT 问题').fill('VPN 连不上，提示认证超时，怎么排查？');
    await page.getByRole('button',{name:'开始诊断',exact:true}).click();
    await page.getByRole('heading',{name:'诊断结果',exact:true}).waitFor({timeout:120000});
    await page.getByText('人工工单已创建',{exact:true}).waitFor();
    assert.equal((await api('/helpdesk/overview')).open_tickets,ticketCount+1);
    assert.equal(await page.evaluate(()=>sessionStorage.getItem('resolveai_pending_run')),null);
    const latest=(await api('/helpdesk/runs'))[0];
    await page.evaluate(id=>sessionStorage.setItem('resolveai_pending_run',id),latest.id);
    await page.reload();
    await page.getByRole('heading',{name:'诊断结果',exact:true}).waitFor();
    assert.equal((await api('/helpdesk/overview')).open_tickets,ticketCount+1);
    await page.getByRole('button',{name:'运行记录',exact:true}).click();
    await page.getByRole('button',{name:'填入问题重试',exact:true}).first().waitFor();
    await page.screenshot({path:path.join(root,'docs/resolveai-run-history.png'),fullPage:false});
    assert.deepEqual(errors,[]);
    console.log(JSON.stringify({passed:true,source:code,checks:['UTF-8 Markdown import','knowledge edit and reindex','preview without run/ticket creation','archive removes chunks','restore as new version','knowledge JSON download','390px knowledge editor','real stream disconnect result recovery','reload result recovery','no duplicate ticket','history retry controls','no page exceptions']},null,2));
  }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
